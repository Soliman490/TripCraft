package com.tripcraft.app.features.export

import android.content.Context
import android.content.Intent
import com.tripcraft.app.ItineraryItem
import com.tripcraft.app.PackingItem
import com.tripcraft.app.data.expense.ExpenseEntity
import com.tripcraft.app.data.journal.JournalNoteEntity
import com.tripcraft.app.features.trips.TripEntity
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object TripExporter {

    fun exportTripReport(
        context: Context,
        trip: TripEntity,
        itineraryList: List<ItineraryItem>,
        expenseList: List<ExpenseEntity>,
        packingList: List<PackingItem>,
        journalNotes: List<JournalNoteEntity>,
        currencySymbol: String = "EGP"
    ) {
        val dateFormat = SimpleDateFormat("dd MMM yyyy", Locale.getDefault())
        val startDateStr = dateFormat.format(Date(trip.startDate))
        val endDateStr = dateFormat.format(Date(trip.endDate))

        val totalExpenses = expenseList.sumOf { it.amount }

        val itineraryText = itineraryList.ifEmpty { emptyList() }.joinToString("\n") { item ->
            "  • [${item.day} ${item.time}] ${item.title} - ${if (item.done) "✓ Completed" else "⏳ Pending"}"
        }

        val expensesText = expenseList.ifEmpty { emptyList() }.joinToString("\n") { expense ->
            "  • ${expense.title} (${expense.category}): $currencySymbol${expense.amount}"
        }

        val packingText = packingList.ifEmpty { emptyList() }.joinToString("\n") { item ->
            "  • ${item.name} (${item.category}) - ${if (item.packed) "✓ Packed" else "☐ Unpacked"}"
        }

        val journalText = journalNotes.ifEmpty { emptyList() }.joinToString("\n") { note ->
            "  • ${note.title} (${note.location}) - Rating: ${note.rating}/5\n    ${note.description}"
        }

        val report = buildString {
            appendLine("=========================================")
            appendLine("           TRIPCRAFT SUMMARY REPORT      ")
            appendLine("=========================================")
            appendLine("Trip Name: ${trip.title}")
            appendLine("Destination: ${trip.destination}")
            appendLine("Dates: $startDateStr to $endDateStr")
            appendLine("Total Expenses: $currencySymbol$totalExpenses")
            appendLine()
            appendLine("--- ITINERARY ---")
            appendLine(itineraryText.ifBlank { "  No itinerary items." })
            appendLine()
            appendLine("--- EXPENSES ---")
            appendLine(expensesText.ifBlank { "  No expenses recorded." })
            appendLine()
            appendLine("--- PACKING LIST ---")
            appendLine(packingText.ifBlank { "  No packing items." })
            appendLine()
            appendLine("--- TRAVEL JOURNAL NOTES ---")
            appendLine(journalText.ifBlank { "  No journal notes." })
            appendLine()
            appendLine("=========================================")
            appendLine("Generated by TripCraft App")
        }

        val sendIntent = Intent().apply {
            action = Intent.ACTION_SEND
            putExtra(Intent.EXTRA_TEXT, report)
            putExtra(Intent.EXTRA_SUBJECT, "Trip Report: ${trip.title}")
            type = "text/plain"
        }

        val shareIntent = Intent.createChooser(sendIntent, "Share Trip Summary Report")
        context.startActivity(shareIntent)
    }
}
